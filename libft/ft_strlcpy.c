#include "libft.h"

size_t	ft_strlcpy(char *dest, const char *src, size_t size)
{
	unsigned int	i;
	size_t			len_s;

	i = 0;
	len_s = 0;
	while (src[len_s])
		len_s++;
	if (!dest || size == 0)
		return (len_s);
	while (i < size - 1 && src[i])
	{
		dest[i] = src[i];
		i++;
	}
	dest[i] = '\0';
	return (len_s);
}
